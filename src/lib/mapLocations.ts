export function buildMapLocations(
  events: readonly TimelineEvent[]
): MapLocation[] {
  const eventById = new Map(events.map((event) => [event.id, event]));

  return MAP_LOCATION_ASSIGNMENTS.flatMap((assignment) => {
    const event = eventById.get(assignment.eventId);
    if (!event) return [];

    const place = MAP_PLACES[assignment.placeId];

    return [
      {
        id: `${assignment.eventId}-${assignment.placeId}`,
        eventId: event.id,
        eventTitle: event.title,
        eventHref: getEventPath(event.id, event.title),
        eventDateLabel: formatEventDate(event),
        category: event.category ?? null,
        historicalYear: getEventTimelineYear(event),
        latitude: place.latitude,
        longitude: place.longitude,
        placeId: assignment.placeId,
        placeName: place.name,
        locationRole: place.locationRole,
        precision: place.precision,
      },
    ];
  });
}
